// Generate slots for each doctor across the next 14 days
export function generateInitialSlots(doctors: Doctor[]): DoctorSlot[] {
  const slots: DoctorSlot[] = [];
  const times = ['09:30', '10:30', '11:30', '14:30', '15:30', '16:30'];

  doctors.forEach((doc) => {
    // Generate for next 14 days
    for (let day = 1; day <= 14; day++) {
      const dateStr = getDateOffset(day);
      times.forEach((startTime, idx) => {
        const [h, m] = startTime.split(':').map(Number);
        const endMinutes = m + 30;
        const endTime = `${String(h + Math.floor(endMinutes / 60)).padStart(2, '0')}:${String(endMinutes % 60).padStart(2, '0')}`;
        const slotType: ConsultationType = (idx % 2 === 0 && doc.availableTypes.includes('CLINIC'))
          ? 'CLINIC'
          : (doc.availableTypes.includes('ONLINE') ? 'ONLINE' : 'CLINIC');

        slots.push({
          id: `slot_${doc.id}_d${day}_t${idx}`,
          doctorId: doc.id,
          date: dateStr,
          startTime,
          endTime,
          type: slotType,
          isBooked: false,
        });
      });
    }
  });

  return slots;
}

